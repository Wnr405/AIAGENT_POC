#!/usr/bin/env node
// Requirements traceability (02-SRS §11.3): every requirement ID in 01/02 must be
// referenced by at least one automated test, or be listed in trace-exemptions.json
// with where it is verified instead (CI job, infra config, manual review).
// Usage: node harness/trace-requirements.mjs [--check] [--write]
import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isSpec, read, rel, ROOT, walk } from './lib.mjs';

const ID = /\b(BR-\d{2}|UR-[A-Z]\d{2}|FR-[A-Z]+-\d{2}|NFR-[A-Z0-9]+-\d{2}|SEC-\d{2}|CN-\d{2})\b/g;
const specDocs = readdirSync(ROOT).filter((f) => /^0[12]-.*\.md$/.test(f));
if (specDocs.length === 0) {
  console.error('requirements documents 01-*.md / 02-*.md not found at repo root');
  process.exit(1);
}

/** id → first table-row description */
const requirements = new Map();
for (const doc of specDocs) {
  for (const line of read(join(ROOT, doc)).split('\n')) {
    const m = line.match(/^\|\s*((?:BR|UR|FR|NFR|SEC|CN)-[A-Z0-9-]+)\s*\|\s*([^|]+)\|/);
    if (m && !requirements.has(m[1])) requirements.set(m[1], { doc, text: m[2].trim().replace(/\s+/g, ' ').slice(0, 110) });
  }
}

const exemptions = JSON.parse(read(join(ROOT, 'harness/trace-exemptions.json')));
const testFiles = ['cms-api', 'cms-web'].flatMap((p) => walk(join(ROOT, p), (f) => isSpec(f) && /\.(ts|tsx)$/.test(f)));
const refs = new Map();
/** Expands shorthand used in test titles: "FR-AUTH-07/08", "UR-A01..A05", "FR-CONTENT-08/09". */
function idsIn(text) {
  const out = new Set(text.match(ID) ?? []);
  const re = /\b((?:FR-[A-Z]+|NFR-[A-Z0-9]+|UR-[A-Z]|BR|SEC|CN)-?)(\d{2})((?:\/\d{2})+|\.\.[A-Z]?(\d{2}))/g;
  let m;
  while ((m = re.exec(text))) {
    const prefix = m[1].endsWith('-') || /^UR-[A-Z]$/.test(m[1]) ? m[1] : `${m[1]}-`;
    const join = (n) => (/^UR-[A-Z]$/.test(m[1]) ? `${m[1]}${n}` : `${prefix}${n}`);
    if (m[3].startsWith('/')) [m[2], ...m[3].slice(1).split('/')].forEach((n) => out.add(join(n)));
    else for (let n = Number(m[2]); n <= Number(m[4]); n++) out.add(join(String(n).padStart(2, '0')));
  }
  return out;
}
for (const f of testFiles) {
  for (const id of idsIn(read(f))) refs.set(id, [...(refs.get(id) ?? []), rel(f)]);
}

const rows = [];
const missing = [];
for (const [id, { doc, text }] of requirements) {
  const tests = refs.get(id) ?? [];
  const exempt = exemptions[id];
  const status = tests.length ? 'tested' : exempt ? 'verified-elsewhere' : 'MISSING';
  if (status === 'MISSING') missing.push(id);
  rows.push(`| ${id} | ${text.replace(/\|/g, '/')} | ${status} | ${tests.length ? tests.map((t) => `\`${t.split('/').pop()}\``).join(', ') : (exempt ?? '—')} |`);
}

const tested = rows.filter((r) => r.includes('| tested |')).length;
const summary = `${requirements.size} requirements · ${tested} referenced by tests · ${requirements.size - tested - missing.length} verified elsewhere · ${missing.length} missing`;
if (process.argv.includes('--write')) {
  const out = [
    '# Requirements Traceability Matrix',
    '',
    '> Generated by `node harness/trace-requirements.mjs --write` — do not edit by hand.',
    '> A requirement is *tested* when its ID appears in at least one test file (test names cite IDs, e.g. `FR-AUTH-06`).',
    '',
    `**${summary}**`,
    '',
    '| ID | Requirement (excerpt) | Status | Evidence |',
    '| -- | --------------------- | ------ | -------- |',
    ...rows,
    '',
  ].join('\n');
  writeFileSync(join(ROOT, 'cms-docs/TRACEABILITY.md'), out);
}
console.log(`${missing.length ? '✗' : '✓'} traceability: ${summary}`);
if (missing.length) console.log(`  missing: ${missing.join(', ')}`);
if (process.argv.includes('--check') && missing.length) process.exit(1);
if (!existsSync(join(ROOT, 'cms-docs'))) process.exit(0);
